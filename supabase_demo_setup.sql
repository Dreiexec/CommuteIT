-- Profile names are editable by the signed-in account owner.
-- Existing accounts can use the Settings > Change your name option without
-- needing a new account; the frontend upserts the profile row on save.


-- Registered account profile bootstrap for editable CommuteIT names.
-- Anonymous/demo users are intentionally excluded.
create or replace function public.handle_new_commuteit_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if coalesce(new.is_anonymous, false) then
    return new;
  end if;

  insert into public.profiles (user_id, first_name, last_name)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'first_name', ''), split_part(coalesce(new.email, 'Commuter'), '@', 1)),
    coalesce(new.raw_user_meta_data ->> 'last_name', '')
  )
  on conflict (user_id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created_commuteit on auth.users;
create trigger on_auth_user_created_commuteit
after insert on auth.users
for each row execute function public.handle_new_commuteit_user();

-- Backfill profile rows for existing registered accounts.
insert into public.profiles (user_id, first_name, last_name)
select
  u.id,
  coalesce(nullif(u.raw_user_meta_data ->> 'first_name', ''), split_part(coalesce(u.email, 'Commuter'), '@', 1)),
  coalesce(u.raw_user_meta_data ->> 'last_name', '')
from auth.users u
where coalesce(u.is_anonymous, false) = false
  and not exists (select 1 from public.profiles p where p.user_id = u.id);
