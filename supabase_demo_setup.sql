-- CommuteIT Supabase demo setup
-- Run this in Supabase SQL Editor AFTER enabling Anonymous Sign-Ins:
-- Authentication > Providers > Anonymous Sign-Ins > Enable
--
-- The demo uses signInAnonymously(), so no real email/password is required.
-- Each demo login receives a fresh authenticated user. On logout the frontend
-- deletes that user's saved routes, trips, and profile rows, then signs out.

create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  first_name text not null default 'Drei',
  last_name text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Safe migration for existing CommuteIT databases whose profiles table was
-- created before the editable-name fields were added.
alter table public.profiles
  add column if not exists first_name text;
alter table public.profiles
  add column if not exists last_name text;
alter table public.profiles
  alter column first_name set default 'Commuter';
alter table public.profiles
  alter column last_name set default '';


