-- Secure aggregate function: returns route-level statistics only, never user IDs.
create or replace function public.get_public_route_stats()
returns table(route text, trip_count bigint, avg_distance numeric, avg_duration numeric, avg_co2 numeric)
language sql
security definer
set search_path = public
as $$
  select
    concat(from_location, ' → ', to_location) as route,
    count(*) as trip_count,
    round(avg(distance_km), 2) as avg_distance,
    round(avg(duration_min), 1) as avg_duration,
    round(avg(co2), 2) as avg_co2
  from public.trips
  group by from_location, to_location
  order by count(*) desc
  limit 10;
$$;
revoke all on function public.get_public_route_stats() from public;
grant execute on function public.get_public_route_stats() to authenticated;

